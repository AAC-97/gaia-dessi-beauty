const langButtons = document.querySelectorAll("[data-lang]");
const browserLang = navigator.language.toLowerCase().startsWith("it") ? "it" : navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
const storedLang = localStorage.getItem("gaia-site-lang");
const defaultLang = translations[storedLang] ? storedLang : browserLang;

function setLang(lang) {
  const dictionary = translations[lang] || translations.it;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = dictionary[node.dataset.i18n] || translations.it[node.dataset.i18n];
    if (value) node.textContent = value;
  });
  langButtons.forEach((button) => button.classList.toggle("is-active", button.dataset.lang === lang));
  localStorage.setItem("gaia-site-lang", lang);
}

langButtons.forEach((button) => button.addEventListener("click", () => setLang(button.dataset.lang)));
setLang(defaultLang);
